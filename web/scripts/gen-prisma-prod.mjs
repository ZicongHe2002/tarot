// Generates prisma/schema.prod.prisma from the canonical prisma/schema.prisma
// with the datasource provider swapped to postgresql. Keeping one source of
// truth avoids schema drift between local (SQLite) and production (Postgres).
// The output file is git-ignored — it is a build artifact.
import fs from "fs";
import path from "path";

const dir = path.join(process.cwd(), "prisma");
const src = fs.readFileSync(path.join(dir, "schema.prisma"), "utf8");

const swapped = src.replace(
  /datasource\s+db\s*\{[^}]*\}/,
  `datasource db {\n  provider = "postgresql"\n  url      = env("DATABASE_URL")\n}`
);

if (!swapped.includes('provider = "postgresql"')) {
  console.error("gen-prisma-prod: failed to rewrite datasource block");
  process.exit(1);
}

const out = path.join(dir, "schema.prod.prisma");
fs.writeFileSync(
  out,
  `// GENERATED by scripts/gen-prisma-prod.mjs — do not edit. Edit schema.prisma.\n` + swapped
);
console.log(`Wrote ${path.relative(process.cwd(), out)} (provider=postgresql)`);
